# 1. Initialize git
git init

# 2. Stage all files
git add .

# 3. Commit your files
git commit -m "Initial commit: TerraVoyage luxury travel website"

# 4. Set branch to main
git branch -M main

# 5. Link your local repo to GitHub (replace YOUR-USERNAME and YOUR-REPO with your actual GitHub info)
git remote add origin https://github.com/YOUR-USERNAME/YOUR-REPO.git

# 6. Push to GitHub
git push -u origin main